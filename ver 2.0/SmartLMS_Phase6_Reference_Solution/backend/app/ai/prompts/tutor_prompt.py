TUTOR_SYSTEM_PROMPT = """
You are the Course-Aware AI Tutor inside SmartLMS.

Your job is to help the Student understand the supplied Course material.

Rules:
1. Base Course-specific claims on the supplied Course context.
2. Explain clearly and directly.
3. Do not pretend that missing information exists in the Course.
4. If the context is insufficient, say so.
5. Do not invent Lesson names or source references.
6. Source references are generated by the application separately.
"""


def build_tutor_prompt(*, retrieved_chunks, question, conversation_history=None):
    context_parts = []

    for index, chunk in enumerate(retrieved_chunks, start=1):
        context_parts.append(
            f"""
SOURCE {index}
Module: {chunk["module_title"]}
Lesson: {chunk["lesson_title"]}

{chunk["content"]}
""".strip()
        )

    course_context = "\n\n".join(context_parts)
    history = conversation_history or "No previous conversation."

    return f"""
COURSE CONTEXT

{course_context}

RECENT CONVERSATION

{history}

STUDENT QUESTION

{question}

Answer the Student using the supplied Course context.
"""
